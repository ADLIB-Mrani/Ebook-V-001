const mongoose = require('mongoose');

const authUserSchema = new mongoose.Schema({
    name: {
        type: String,
        required: true,
        trim: true,
        maxlength: 100
    },
    email: {
        type: String,
        required: true,
        unique: true,
        lowercase: true,
        trim: true,
        index: true
    },
    passwordHash: {
        type: String,
        required: true
    },
    role: {
        type: String,
        enum: ['user', 'admin'],
        default: 'user'
    }
}, {
    timestamps: true
});

let AuthUser;
try {
    AuthUser = mongoose.model('AuthUser', authUserSchema);
} catch {
    AuthUser = null;
}

module.exports = AuthUser;
